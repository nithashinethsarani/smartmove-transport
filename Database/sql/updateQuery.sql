SELECT 'TRIP' AS TBL, TRIP_ID AS ID,
       VEHICLE_ID||' / '||DRIVER_ID||' / '||ROUTE_ID||' / '||TO_CHAR(TRIP_DATE,'YYYY-MM-DD')||' / '||STATUS||' / '||PRICE AS DETAILS
FROM TRIP
UNION ALL

SELECT 'PASSENGER', PASSENGER_ID, FIRST_NAME||' / '||EMAIL FROM PASSENGER
UNION ALL

SELECT 'TICKET', TICKET_ID, TRIP_ID||' / '||PASSENGER_ID||' / '||SEAT_NUMBER FROM TICKET
UNION ALL

SELECT 'PAYMENT', PAYMENT_ID, TICKET_ID||' / '||PAYMENT_STATUS FROM PAYMENT
UNION ALL

SELECT 'FEEDBACK', FEEDBACK_ID, TRIP_ID||' / '||RATING FROM FEEDBACK
ORDER BY 1, 2;







