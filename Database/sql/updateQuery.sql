CREATE SEQUENCE SEQ_PAYMENT START WITH 100 INCREMENT BY 1;

CREATE OR REPLACE TRIGGER trg_after_ticket_insert
AFTER INSERT ON TICKET
FOR EACH ROW
BEGIN
    INSERT INTO PAYMENT (PAYMENT_ID, TICKET_ID, PAYMENT_DATE, AMOUNT, PAYMENT_METHOD, PAYMENT_STATUS)
    VALUES ('PM' || LPAD(SEQ_PAYMENT.NEXTVAL, 3, '0'),
            :NEW.TICKET_ID, SYSDATE, :NEW.TICKET_PRICE, 'Pending', 'Pending');
END;




SELECT OBJECT_NAME, STATUS FROM USER_OBJECTS
WHERE OBJECT_NAME IN ('TRG_AFTER_TICKET_INSERT','SEQ_PAYMENT');




